#
# - 문제를 풀면서 실제로 증명된 구조
# - 이 문제에서 발견한 구체적인 관계
# - 이후 정수론 문제에서 시도해볼 만한 탐색 행동
#
# 을 구분해서 본다.
#
#
# ================================================================
# 1. GCD / 유클리드 호제법
# ================================================================
#
# [출발할 때 활용할 수 있는 정수론적 표현]
#
# p가 A, B의 공약수라는 말은
#
#     A = p*A'
#     B = p*B'
#
# 로 표현할 수 있다.
#
# 즉 "둘 다 p로 나누어진다"는 조건을
# 실제 대수식으로 바꾸어 조작할 수 있다.
#
#
# [이 문제에서 발견한 관계]
#
# 위 식에서
#
#     A - B = p*(A' - B')
#
# 이므로 A와 B를 모두 나누는 p는 A-B도 나눈다.
#
# 반대로 p가 A-B와 B를 모두 나눈다면
#
#     A = (A-B) + B
#
# 이므로 p는 A도 나눈다.
#
# 따라서 정확히는
#
#     (A, B)의 공약수 집합
#       ==
#     (A-B, B)의 공약수 집합
#
# 이다.
#
#
# 같은 관계를 반복하면
#
#     A - n*B
#
# 로 바꾸어도 공약수 집합을 유지할 수 있다.
#
# 이 값을 0 이상이면서 최대한 작게 만들면
#
#     A - n*B = A % B
#
# 이므로
#
#     gcd(A, B) = gcd(B, A % B)
#
# 를 얻는다.
#
#
# [여기서부터는 발견한 변환의 논리적 귀결]
#
#     0 <= A % B < B
#
# 이므로
#
#     (A, B) -> (B, A % B)
#
# 를 반복할 때 두 번째 값은
# 0 이상의 정수이면서 계속 감소한다.
#
# 따라서 반드시 어떤
#
#     (X, 0)
#
# 에 도달한다.
#
# 모든 양의 정수 p는 0을 나누므로,
# (X, 0)의 공약수가 되기 위한 실제 조건은 p가 X를 나누는 것뿐이다.
#
# 따라서
#
#     gcd(X, 0) = X
#
# 이고, 각 state에서 공약수 집합을 보존했으므로
# 최초 (A, B)의 GCD 역시 X이다.
#
#
# ------------------------------------------------
# GCD에서 재사용할 만한 탐색 행동
# ------------------------------------------------
#
# "더 단순하게 만들 수 있는가?"만 생각하는 것은 너무 추상적이다.
#
# 정수론 문제에서 약수/배수 관계가 핵심이라면 먼저
#
#     p | A  <=>  A = p*k
#
# 처럼 조건을 대수식으로 풀어 써본다.
#
# 여러 값이 같은 p로 나누어진다면,
# 합, 차, 정수배 등의 조작에서도 그 관계가 유지되는지 확인해볼 수 있다.
#
# 보존되는 조작을 실제로 발견한 뒤에는
#
#     - 그 조작으로 상태를 단순화할 수 있는가?
#     - 같은 조작을 반복할 수 있는가?
#     - 반복을 하나의 연산으로 압축할 수 있는가?
#     - 상태가 정말 종료하는가?
#
# 를 분석한다.
#
#
# 주의:
#
# X "공약수 문제에서는 두 수를 빼본다."
#   -> A-B는 이 문제에서 발견한 구체적인 관계이다.
#
# X "수를 최대한 줄여서 0을 만든다."
#   -> 0은 처음부터 목표로 정한 것이 아니라,
#      (B, A%B)라는 변환을 발견한 뒤 감소성을 분석해서 얻은 결과이다.
#
#
# ================================================================
# 2. Extended GCD
# ================================================================
#
# 목표는
#
#     a*x + b*y = gcd(a, b)
#
# 를 만족하는 정수 x, y를 찾는 것이다.
#
#
# ------------------------------------------------
# 자연스러운 출발점
# ------------------------------------------------
#
# 식에서 이미 알고 있는 구조는 우변의 gcd(a, b)이다.
#
# 일반 GCD에서
#
#     gcd(a, b)
#       = gcd(b, a % b)
#       = gcd(a % b, b % (a % b))
#       = ...
#       = gcd(X, 0)
#
# 처럼 같은 GCD 값을 유지하면서 state를 계속 바꿀 수 있다는 것을 알고 있다.
#
# 따라서 Extended GCD에서도 우선
#
#     "ax + by = gcd(a, b)"
#
# 의 우변에 이미 알고 있는 GCD의 상태 변환을 적용해보고,
#
#     "식 전체도 다음 state의 두 수를 기준으로 다시 표현할 수 있는가?"
#
# 를 확인해볼 수 있다.
#
# 여기서
#
#     gcd 값이 모든 state에서 같다
#
# 는 사실만으로
#
#     모든 state에서 gcd를 그 두 수의 정수 선형결합으로 표현할 수 있다
#
# 는 결론이 자동으로 나오는 것은 아니다.
#
# 실제로 표현을 변환할 수 있는지는 별도로 확인해야 한다.
#
#
# ------------------------------------------------
# 종단 state
# ------------------------------------------------
#
# GCD 변환은 반드시
#
#     (a, 0)
#
# 형태의 종단점에 도달한다.
#
# 여기서는
#
#     gcd(a, 0) = a
#
# 이므로
#
#     a*1 + 0*0 = a
#
# 로 실제 해 하나를 바로 만들 수 있다.
#
# 따라서
#
#     x = 1
#     y = 0
#
# 을 base case의 해로 선택할 수 있다.
#
# y는 실제로 아무 정수여도 되지만
# 구현에서는 대표값으로 0을 선택한다.
#
#
# ------------------------------------------------
# 다음 state의 표현을 이전 state로 되돌리기
# ------------------------------------------------
#
# 다음 state인
#
#     (b, a % b)
#
# 에서 이미
#
#     b*x_new + (a % b)*y_new
#       = gcd(b, a % b)
#       = gcd(a, b)
#
# 를 만족하는 해를 얻었다고 하자.
#
# 나머지의 정의는
#
#     a = (a // b)*b + a % b
#
# 즉
#
#     a % b = a - (a // b)*b
#
# 이다.
#
# 이를 대입하면
#
#     b*x_new + (a % b)*y_new
#
#   = b*x_new
#     + (a - (a // b)*b)*y_new
#
#   = a*y_new
#     + b*(x_new - (a // b)*y_new)
#
# 이다.
#
# 따라서 이전 state (a, b)의 계수는
#
#     x = y_new
#     y = x_new - (a // b)*y_new
#
# 로 복원할 수 있다.
#
#
# ------------------------------------------------
# 정수해가 항상 존재하는 이유
# ------------------------------------------------
#
# "ax + by는 gcd(a,b)의 배수이다"라는 사실만으로는
#
#     ax + by = gcd(a,b)
#
# 인 정수해가 실제로 존재한다고 보장할 수 없다.
#
# 존재성은 다음 구조에서 나온다.
#
# 1. 종단 state (a, 0)에서는 실제 정수해 하나를 직접 만들 수 있다.
#
# 2. 다음 state의 정수해를 알고 있으면,
#    위의 식을 이용해 이전 state의 정수해로 항상 변환할 수 있다.
#
# 따라서 종단점의 해를 재귀적으로 이전 state들에 되돌려주면
# 최초 (a, b)에 대해서도 반드시 정수해 하나를 얻을 수 있다.
#
#
# ------------------------------------------------
# Extended GCD에서 재사용할 만한 탐색 행동
# ------------------------------------------------
#
# 이 문제에서는 식에 gcd(a, b)가 직접 나타나 있으므로,
# 먼저 이미 알고 있는 gcd의 성질과 상태 변환을 활용할 수 있는지 본 것이 자연스럽다.
#
# 보다 일반적으로는,
#
# - 문제 식 안에 이미 알고 있는 수학적 대상/성질이 들어 있다면
#   그 대상이 가진 변환이나 불변성을 먼저 활용해볼 수 있다.
#
# - 같은 값을 유지하면서 더 작은 문제로 변환할 수 있다면,
#   최종 값뿐 아니라 "구성해야 하는 해"도
#   state 사이에서 변환할 수 있는지 확인한다.
#
# - 종단 state에서 해를 직접 만들 수 있고
#   다음 state의 해 -> 이전 state의 해 변환이 가능하다면,
#   전체 해를 재귀적으로 구성할 수 있다.
#
#
# 주의:
#
# X "재귀 문제에서는 작은 해를 큰 해로 복원하면 된다."
#   -> 너무 일반적인 문장이고, 실제로 복원 관계가 존재하는지는 문제마다 발견해야 한다.
#
# X "x = y_new,
#     y = x_new - q*y_new 를 기억한다."
#   -> Extended GCD에 특화된 결과이다.
#
# O 이 문제에서는 우변의 gcd가 이미 알고 있는 구조였기 때문에,
#   gcd의 state 변환을 식 전체에 적용할 수 있는지를 조사한 것이
#   실제 문제에서 출발할 수 있는 비교적 구체적인 탐색 방향이었다.
#
#
# ================================================================
# 3. 회고할 때 구분할 것
# ================================================================
#
# [지식]
# - p | A <=> A = p*k
# - 0 <= A % B < B
# - gcd(a, 0) = a
#
# [이 문제에서의 발견]
# - (A, B)와 (A-B, B)의 공약수 집합이 같다.
# - 반복 뺄셈을 A % B로 압축할 수 있다.
