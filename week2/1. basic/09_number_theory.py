def gcd(a, b):
    """
    유클리드 호제법을 사용한 최대공약수 계산
    
    Args:
        a, b: 두 양의 정수
    
    Returns:
        최대공약수
    """
    # 두 공약수를 확인하기 위해, 최대한 수를 줄이고 싶다는 것 
    #  두 수 A, B ( A > B)에 대해, 모든 공약수 p는 A= p*A', B = p*B'
    #  그렇다면, A - B = p ( A' - B')
    # 그렇다면 A - B는 공약수 p의 배수이다. 즉 A - B는 p를 약수로 가진다.
    #  그렇다면 A, B, A - B는 모두 같은 공약수 집합을 가진다.
    #  A > B  and A > A - B 이므로, 
    #  ( A- B, B) or vice versa (크기 차에 따라 ) 하면 더 작은 수로 비교할 수 있다.
    # 그렇다면, A - B*n = p( A' - B'n) 이다. 그렇다면 n이 결과가 0 이상이기 전까지 최대로 둘 수 있다. 
    #  이는 A - B*n 이 A % B 와 의미가 같아짐을 뜻한다.
    #  이제 A, B, A - B, A % B 는 같은 공약수 집합을 가진다. 
    #  B, A % B에 대해, 나머지는  0 <= , < B 이므로, 
    #  (B, A%B) 를 다시 비교할 수 있다.
    #  한번만 적용해보면, B % ( A % B) 이다. 이 값은 A % B 보다 항상 작으므로, 연산을 반복하면 무조건 0으로 감소한다.
    #  그렇다면, 이 상황을 그대로 이어서 나온 두 수 X, 0 에 대해 다시 나누는 수 p를 생각해보자. 
    #   0은 모든 p에 대해서 나누어 떨어지므로, 결국 X의 약수가 적용하며 모든 쌍에 대해 공약수임을 알 수 있다.
    #  따라서 X는 초기 A, B 의 최대 공약수이다.


    # TODO: 유클리드 호제법 구현
    # base case: b가 0이면 a 반환
    # recursive를 이용 
    if b == 0:
        return a

    return gcd(b, a %b)

def extended_gcd(a, b) -> tuple:
    """
    확장 유클리드 호제법
    ax + by = gcd(a, b)를 만족하는 x, y를 찾음
    
    Args:
        a, b: 두 양의 정수
    
    Returns:
        (gcd, x, y) 튜플                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                              
    """
    # TODO: 확장 유클리드 호제법 구현
    # base case: b가 0이면 (a, 1, 0) 반환    
    # recursive case
    # 역추적하며 x, y 계산
    pass
    # 두 해 구하기 - (느낌 ) 하나씩 해볼 수 밖에 없다
    # 하나가 고정되면, 상수 시간 안에 하나가 정해진다. -> x, y는 정수라 어디서 멈춰야 할지 모른다
# ----------------------------------------------------------------


    # ax + by = gcd(a, b)에서 활용해볼 만한 것은 gcd(a, b)의 특성이다.
    # gcd는  대해 모든 state에서 공약수 - 약수 집합이 같다. 
    #  그렇다면 ax + by = gcd(a, b) = gcd (b, a%b) ... = gcd( .. , 0) 까지 갈 수 있다.

    # gcd를 계속 수행하면 (a, b) 에서 0이 되는 경우로 감소할 것이기 때문에, 종단점이 항상 존재한다.
    #  이때 b == 0일 때,  ax + by = gcd(a, 0) = a 이고, y는 부정, 문제에서는 y를 0으로 지정했다. 실제로는 다른 값을 넣어도 타당한 결과가 나온다.
    #  종단점이 항상 해를 반환하기 때문에, 이전 state들은 값이 정해질 수 있다.


    #  그렇다면 각 gcd에 대해, 해당 쌍으로 표현할 수 있을 것
    #   ax + by = gcd (a, b)
    #   gcd (b, a%b) 로 표현하기 위해 나머지 연산을 활용한다: a = (a // b) * b + a % b
    #  그렇다면 b ( y + a//b x) + a%b (x) = gcd (b, a%b) 이다. 
    #  x_new = y + a//b x, y_new = x  이다. ( 이때 아래첨자 없는 수는 모두 이전 state의 것) 
    #  그렇다면, 호출자 (이전 state)는 받아온 x_new, y_new 만 있다면 나머지 수를 알기 때문에 조립할 수 있다.
    #  -> x = y_new , y = x_new - a//b * y_new    


    if b == 0:
        return a, 1, 0

    gcd, x_sub, y_sub = extended_gcd(b, a%b)

    return gcd, y_sub, x_sub - (a//b) * y_sub


def is_prime(n):
    """
    소수 판별
    
    Args:
        n: 판별할 양의 정수
    
    Returns:
        소수이면 True, 아니면 False
    """
    # TODO: 소수 판별 구현
    # n이 2보다 작으면 False
    # 2부터 sqrt(n)까지 나누어 떨어지는지 확인
    # 3부터 sqrt(n)까지 홀수만 확인
    pass 
    if n < 2:
        return False
    for div in range(2, int(sqrt(n)) + 1, 2):
        if n % div == 0:
            return False

    return True

